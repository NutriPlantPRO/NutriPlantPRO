  WITH CHECK (public.is_admin_user());

DROP POLICY IF EXISTS "airci_canopy_trees_admin_all" ON public.airci_canopy_trees;
CREATE POLICY "airci_canopy_trees_admin_all"
  ON public.airci_canopy_trees FOR ALL
  TO authenticated
  USING (public.is_admin_user())
  WITH CHECK (public.is_admin_user());

COMMENT ON TABLE public.airci_detect_jobs IS
  'AirCI: cola y progreso de análisis profesional por vuelo.';
COMMENT ON TABLE public.airci_canopy_trees IS
  'AirCI: una fila por árbol/copa para resultados grandes y consultas por viewport.';

-- Promoción atómica: el resultado anterior sigue vigente hasta que el nuevo
-- tenga todos sus árboles guardados.
CREATE OR REPLACE FUNCTION public.airci_promote_canopy_result(p_result_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_flight_id uuid;
BEGIN
  SELECT flight_id
    INTO v_flight_id
  FROM public.airci_canopy_results
  WHERE id = p_result_id;

  IF v_flight_id IS NULL THEN
    RAISE EXCEPTION 'Resultado AirCI inválido o sin flight_id';
  END IF;

  UPDATE public.airci_canopy_results
     SET is_current = false,
         updated_at = now()
   WHERE flight_id = v_flight_id
     AND id <> p_result_id
     AND is_current;

  UPDATE public.airci_canopy_results
     SET is_current = true,
         updated_at = now()
   WHERE id = p_result_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Resultado AirCI no encontrado';
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.airci_promote_canopy_result(uuid) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.airci_promote_canopy_result(uuid) FROM anon;
REVOKE ALL ON FUNCTION public.airci_promote_canopy_result(uuid) FROM authenticated;
GRANT EXECUTE ON FUNCTION public.airci_promote_canopy_result(uuid) TO service_role;
